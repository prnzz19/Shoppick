use App\Http\Controllers\BuyerSellerMessageController;
use App\Http\Controllers\SellerApplicationController;
use Illuminate\Support\Facades\Route;
use App\Http\Controllers\MarketplaceChatController;

Route::middleware(['auth', 'registration.approved', 'role:buyer,seller'])->group(function () {
    Route::get('seller/apply', [SellerApplicationController::class, 'create'])->name('seller.apply');
    Route::post('seller/apply', [SellerApplicationController::class, 'store'])->name('seller.apply.store');
});

Route::prefix('seller')->name('seller.')->middleware(['auth', 'registration.approved', 'role:seller', \App\Http\Middleware\EnsureApprovedSeller::class])->group(function () {
    Route::get('chat', [MarketplaceChatController::class,'index'])->name('chat.index');
    Route::post('chat/support', [MarketplaceChatController::class,'startSupport'])->name('chat.support');
    Route::get('chat/{conversation}', [MarketplaceChatController::class,'show'])->name('chat.show');
    Route::post('chat/{conversation}/messages', [MarketplaceChatController::class,'send'])->middleware('throttle:30,1')->name('chat.messages.store');
    Route::get('dashboard', DashboardController::class)->name('dashboard');
    Route::get('products', [CenterController::class, 'products'])->name('products.index');
    Route::get('products/{product}/archived', [ProductController::class, 'showArchived'])->withTrashed()->name('products.archived.show');
    Route::post('products/{product}/restore', [ProductController::class, 'restore'])->withTrashed()->name('products.restore');
    Route::delete('products/{product}/permanent', [ProductController::class, 'forceDestroy'])->withTrashed()->name('products.force-destroy');
    Route::resource('products', ProductController::class)->except(['show','index']);
    Route::post('products/{product}/publication', [ProductController::class, 'publication'])->name('products.publication');
    Route::get('orders', [CenterController::class, 'orders'])->name('orders.index');
    Route::get('orders/{sellerOrder}', [OrderController::class, 'show'])->name('orders.show');
    Route::post('orders/{sellerOrder}/status', [OrderController::class, 'update'])->name('orders.status');
    Route::get('waybills', [WaybillController::class, 'index'])->name('waybills.index');
    Route::post('waybills/{sellerOrder}/generate', [WaybillController::class, 'generate'])->name('waybills.generate');
    Route::get('waybills/{shipment}/print', [WaybillController::class, 'print'])->name('waybills.print');
    Route::get('waybills/{shipment}/pdf', [WaybillController::class, 'pdf'])->name('waybills.pdf');
    Route::get('waybills/{shipment}', [WaybillController::class, 'show'])->name('waybills.show');
    Route::get('messages', [BuyerSellerMessageController::class, 'sellerIndex'])->name('messages.index');
    Route::post('messages/start/{sellerOrder}', [BuyerSellerMessageController::class, 'sellerStart'])->middleware('throttle:12,1')->name('messages.start');
    Route::get('messages/{conversation}', [BuyerSellerMessageController::class, 'sellerShow'])->whereNumber('conversation')->name('messages.show');
    Route::get('messages/{conversation}/updates', [BuyerSellerMessageController::class, 'sellerUpdates'])->whereNumber('conversation')->name('messages.updates');
    Route::get('messages/{conversation}/attachments/{attachment}', [BuyerSellerMessageController::class, 'sellerAttachment'])->whereNumber(['conversation', 'attachment'])->name('messages.attachment');
    Route::get('messages/{conversation}/older', [BuyerSellerMessageController::class, 'sellerOlder'])->whereNumber('conversation')->name('messages.older');
    Route::post('messages/{conversation}/send', [BuyerSellerMessageController::class, 'sellerSend'])->whereNumber('conversation')->middleware('throttle:30,1')->name('messages.send');
    Route::get('inventory', [InventoryController::class, 'index'])->name('inventory.index');
    Route::post('inventory/{product}', [InventoryController::class, 'update'])->name('inventory.update');
    Route::get('reviews', [CenterController::class, 'reviews'])->name('reviews.index');
    Route::post('reviews/{review}/reply', [SellerReviewController::class, 'reply'])->name('reviews.reply');
    Route::get('sales', [CenterController::class, 'sales'])->name('sales.index');
    Route::get('marketing', [MarketingController::class, 'index'])->name('marketing.index');
    Route::get('marketing/products', [MarketingController::class, 'products'])->name('marketing.products');
    Route::post('marketing/vouchers', [MarketingController::class, 'store'])->name('marketing.vouchers.store');
    Route::put('marketing/vouchers/{voucher}', [MarketingController::class, 'update'])->name('marketing.vouchers.update');
    Route::post('marketing/vouchers/{voucher}/toggle', [MarketingController::class, 'toggle'])->name('marketing.vouchers.toggle');
    Route::get('notifications', [SellerNotificationController::class, 'index'])->name('notifications.index');
    Route::post('notifications/read-all', [SellerNotificationController::class, 'readAll'])->name('notifications.read-all');
    Route::post('notifications/{notification}/read', [SellerNotificationController::class, 'read'])->name('notifications.read');
    Route::get('settings', [SettingsController::class, 'index'])->name('settings.index');
    Route::put('settings/account', [SettingsController::class, 'account'])->name('settings.account');
    Route::put('settings/shipping', [SettingsController::class, 'shipping'])->name('settings.shipping');
    Route::put('settings/password', [SettingsController::class, 'password'])->name('settings.password');
    Route::get('store/settings', [StoreController::class, 'edit'])->name('store.edit');
    Route::put('store/settings', [StoreController::class, 'update'])->name('store.update');
});
